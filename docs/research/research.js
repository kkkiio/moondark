// MoonDark research 公共脚本：加载 Mermaid 并套用与 research.css 一致的 Anthropic 风格主题。
// 用法：<script defer src="research.js"></script>（普通脚本，file:// 下也能加载）。
import("https://cdn.jsdelivr.net/npm/mermaid@11.17.2/dist/mermaid.esm.min.mjs").then(({ default: mermaid }) => {
  const ink = "#3d3d3a", line = "#5e5d59", paper = "#faf9f5", oat = "#f0eee6", clay = "#d97757";
  mermaid.initialize({
    startOnLoad: false,
    deterministicIds: true,
    theme: "base",
    fontFamily: getComputedStyle(document.documentElement).getPropertyValue("--sans"),
    themeVariables: {
      fontSize: "14px",
      background: paper,
      primaryColor: paper,
      primaryTextColor: ink,
      primaryBorderColor: line,
      secondaryColor: oat,
      tertiaryColor: oat,
      lineColor: line,
      textColor: ink,
      edgeLabelBackground: paper,
      clusterBkg: "transparent",
      clusterBorder: "#b0aea5",
      noteBkgColor: oat,
      noteBorderColor: "#c2c0b6",
      noteTextColor: ink,
      actorBkg: paper,
      actorBorder: line,
      actorTextColor: ink,
      actorLineColor: "#c2c0b6",
      signalColor: line,
      signalTextColor: ink,
      labelBoxBkgColor: oat,
      labelBoxBorderColor: "#c2c0b6",
      labelTextColor: ink,
      loopTextColor: ink,
      sequenceNumberColor: paper,
      quadrant1Fill: oat,
      quadrant2Fill: paper,
      quadrant3Fill: paper,
      quadrant4Fill: paper,
      quadrant1TextFill: ink,
      quadrant2TextFill: ink,
      quadrant3TextFill: ink,
      quadrant4TextFill: ink,
      quadrantPointFill: clay,
      quadrantPointTextFill: ink,
      quadrantTitleFill: ink,
      quadrantXAxisTextFill: line,
      quadrantYAxisTextFill: line,
      quadrantInternalBorderStrokeFill: "#d1cfc5",
      quadrantExternalBorderStrokeFill: line,
    },
    flowchart: { curve: "linear", padding: 16 },
    sequence: { mirrorActors: false, messageMargin: 32, actorMargin: 32, width: 110, height: 44, noteMargin: 8 },
  });
  mermaid.run({ querySelector: ".mermaid" });
});
